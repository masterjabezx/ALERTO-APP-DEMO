#!/bin/sh
set -eu

cd /var/www/html

if [ -z "${APP_KEY:-}" ]; then
    echo "APP_KEY must be generated by the Render Blueprint before startup." >&2
    exit 1
fi

case "$APP_KEY" in
    base64:*) ;;
    *) APP_KEY="base64:${APP_KEY}" ;;
esac
export APP_KEY

mkdir -p \
    storage/app/private \
    storage/app/public \
    storage/framework/cache/data \
    storage/framework/sessions \
    storage/framework/views \
    storage/logs \
    bootstrap/cache

chown www-data:www-data storage/app storage/app/private storage/app/public
chown -R www-data:www-data storage/framework storage/logs bootstrap/cache
chmod -R ug+rwX storage/framework storage/logs bootstrap/cache
chmod ug+rwx storage/app storage/app/private storage/app/public

gosu www-data php artisan optimize --no-interaction
gosu www-data php artisan storage:link --force --no-interaction

: "${PORT:=10000}"
export PORT

envsubst '${PORT}' \
    < /etc/nginx/templates/default.conf.template \
    > /etc/nginx/conf.d/default.conf

nginx -t

exec /usr/bin/supervisord -c /etc/supervisor/conf.d/supervisord.conf
